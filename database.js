db.serialize(() => {
  db.run(`
    CREATE TABLE IF NOT EXISTS users (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      name TEXT,
      email TEXT UNIQUE,
      password TEXT
    )
  `);

  db.run(`
    CREATE TABLE IF NOT EXISTS cars (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      name TEXT,
      brand TEXT,
      category TEXT,
      price REAL,
      fuel_type TEXT,
      fuel_economy REAL,
      reliability_score REAL,
      safety_score REAL,
      comfort_score REAL,
      performance_score REAL,
      seats INTEGER,
      description TEXT
    )
  `);

  const insertCar = db.prepare(`
    INSERT INTO cars (
      name, brand, category, price, fuel_type, fuel_economy,
      reliability_score, safety_score, comfort_score,
      performance_score, seats, description
    )
    SELECT ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?
    WHERE NOT EXISTS (
      SELECT 1 FROM cars WHERE name = ?
    )
  `);

  carsData.forEach((car) => {
    insertCar.run([...car, car[0]], (err) => {
      if (err) {
        console.error('Error inserting car:', car[0], err.message);
      }
    });
  });

  insertCar.finalize(() => {
    db.get('SELECT COUNT(*) AS total FROM cars', (err, row) => {
      if (err) {
        console.error('Error counting cars:', err.message);
      } else {
        console.log(`Database contains ${row.total} cars.`);
      }
    });
  });

  db.get(
    'SELECT id FROM users WHERE email = ?',
    ['demo@autodecision.ai'],
    async (err, row) => {
      if (err) {
        console.error('Error checking demo user:', err.message);
        return;
      }

      if (!row) {
        try {
          const hashedPassword = await bcrypt.hash('123456', 8);

          db.run(
            'INSERT INTO users (name, email, password) VALUES (?, ?, ?)',
            ['أبو نورة', 'demo@autodecision.ai', hashedPassword],
            (insertErr) => {
              if (insertErr) {
                console.error('Error creating demo user:', insertErr.message);
              } else {
                console.log('Demo user created.');
              }
            }
          );
        } catch (hashErr) {
          console.error('Password hashing error:', hashErr.message);
        }
      }
    }
  );
});

